import AppKit
import Combine

public final class ClipboardMonitor: ObservableObject {
    public static let shared = ClipboardMonitor()
    
    @Published public var isMonitoring: Bool = false
    @Published public var ignorePasswordManagers: Bool = true
    
    private var lastChangeCount: Int = 0
    private var timerCancellable: AnyCancellable?
    
    // Concealed / transient types from password managers (1Password, Bitwarden, KeePass, etc.)
    private let transientTypeIdentifiers: [String] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.dstoecker.xkeychain"
    ]
    
    public init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
    }
    
    public func start() {
        guard !isMonitoring else { return }
        self.lastChangeCount = NSPasteboard.general.changeCount
        self.isMonitoring = true
        
        timerCancellable = Timer.publish(every: 0.75, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in
                self?.checkPasteboard()
            }
    }
    
    public func stop() {
        isMonitoring = false
        timerCancellable?.cancel()
        timerCancellable = nil
    }
    
    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        let currentChangeCount = pasteboard.changeCount
        
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount
        
        if ignorePasswordManagers {
            if let types = pasteboard.types {
                for type in types {
                    if transientTypeIdentifiers.contains(type.rawValue) {
                        return
                    }
                }
            }
        }
        
        // Extract string content
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            let type: ClipboardContentType
            if text.hasPrefix("http://") || text.hasPrefix("https://") {
                type = .url
            } else if text.contains("{") && text.contains("}") || text.contains("func ") || text.contains("def ") {
                type = .code
            } else {
                type = .text
            }
            
            let frontmostApp = NSWorkspace.shared.frontmostApplication?.localizedName
            ClipboardHistoryStore.shared.addItem(content: text, type: type, sourceApp: frontmostApp)
        }
    }
    
    public func copyToClipboard(_ content: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(content, forType: .string)
        self.lastChangeCount = pasteboard.changeCount
    }
}
