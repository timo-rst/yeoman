import Foundation
import YeomanCore

func runClipboardTests() {
    let harness = TestHarness.shared
    
    harness.runSuite("Clipboard Privacy & History Tests") {
        harness.test("isTransientPasteboardType identifies sensitive clipboard types") {
            // Standard OS & password manager transient types
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.TransientType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.ConcealedType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.AutoGeneratedType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("de.petermaurer.TransientPasteboardType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("com.agilebits.onepassword"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("com.bitwarden.desktop"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.keepassxc.KeePassXC.transient"))
            
            // Standard non-sensitive types should NOT be flagged as transient
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.utf8-plain-text"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.tiff"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.png"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.html"))
        }
        
        harness.test("isPasswordManagerURL detects web vaults and browser extensions") {
            // Web vaults
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://pass.proton.me/u/0/vault"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://vault.bitwarden.com/#/items"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://my.1password.com/vaults/all"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://app.dashlane.com/"))
            
            // Browser extension URLs
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://ghmbeldphafepmbegfdlkpapadhbakde/popup.html")) // Proton Pass
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://nngceckbapebfimnlniiiahkandclblb/popup.html")) // Bitwarden
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://aeblfdkhhhdcdjpifhhbdiojplfjncoa/options.html")) // 1Password
            
            // Standard benign websites must NOT be flagged
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://developer.apple.com/documentation/swift/"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://github.com/timo-rst/mac_customizer"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://en.wikipedia.org/wiki/Yeomen_Warders"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://news.ycombinator.com/"))
        }
        
        harness.test("ClipboardItem model properties and search matching") {
            let item = ClipboardItem(content: "git commit -m 'Initial release'", type: .code, sourceApp: "Terminal")
            
            assertEqual(item.content, "git commit -m 'Initial release'")
            assertEqual(item.type, .code)
            assertEqual(item.sourceApp, "Terminal")
            assertFalse(item.isPinned)
            
            // Case insensitive query search matching
            let query = "commit"
            assertTrue(item.content.lowercased().contains(query.lowercased()))
            
            let nonMatchingQuery = "swiftui"
            assertFalse(item.content.lowercased().contains(nonMatchingQuery.lowercased()))
        }
    }
}
