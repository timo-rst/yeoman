import Foundation
import AppKit
import YeomanCore

func runClipboardTests() {
    let harness = TestHarness.shared
    
    harness.runSuite("Clipboard Privacy & History Tests") {
        harness.test("isTransientPasteboardType identifies sensitive clipboard types") {
            // Standard OS & password manager transient types
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.TransientType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.ConcealedType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.nspasteboard.AutoGeneratedType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("de.petermaurer.TransientPasteboardType"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("com.agilebits.onepassword"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("com.bitwarden.desktop"))
            assertTrue(ClipboardMonitor.isTransientPasteboardType("org.keepassxc.KeePassXC.transient"))
            
            // Standard non-sensitive types should NOT be flagged as transient
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.utf8-plain-text"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.tiff"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.png"))
            assertFalse(ClipboardMonitor.isTransientPasteboardType("public.html"))
        }
        
        harness.test("isPasswordManagerURL detects web vaults and browser extensions") {
            // Web vaults
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://pass.proton.me/u/0/vault"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://vault.bitwarden.com/#/items"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://my.1password.com/vaults/all"))
            assertTrue(ClipboardMonitor.isPasswordManagerURL("https://app.dashlane.com/"))
            
            // Browser extension URLs
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://ghmbeldphafepmbegfdlkpapadhbakde/popup.html")) // Proton Pass
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://nngceckbapebfimnlniiiahkandclblb/popup.html")) // Bitwarden
            assertTrue(ClipboardMonitor.isPasswordManagerURL("chrome-extension://aeblfdkhhhdcdjpifhhbdiojplfjncoa/options.html")) // 1Password
            
            // Standard benign websites must NOT be flagged
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://developer.apple.com/documentation/swift/"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://github.com/timo-rst/yeoman"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://en.wikipedia.org/wiki/Yeomen_Warders"))
            assertFalse(ClipboardMonitor.isPasswordManagerURL("https://news.ycombinator.com/"))
        }
        
        harness.test("ClipboardItem model properties and search matching") {
            let item = ClipboardItem(content: "git commit -m 'Initial release'", type: .code, sourceApp: "Terminal")
            
            assertEqual(item.content, "git commit -m 'Initial release'")
            assertEqual(item.type, .code)
            assertEqual(item.sourceApp, "Terminal")
            assertFalse(item.isPinned)
            
            // Case insensitive query search matching
            let query = "commit"
            assertTrue(item.content.lowercased().contains(query.lowercased()))
            
            let nonMatchingQuery = "swiftui"
            assertFalse(item.content.lowercased().contains(nonMatchingQuery.lowercased()))
        }
        
        harness.test("isRemotePasteboard detects Apple Universal Clipboard items") {
            let customPb = NSPasteboard.withUniqueName()
            assertFalse(ClipboardMonitor.isRemotePasteboard(customPb))
            customPb.declareTypes([NSPasteboard.PasteboardType(ClipboardMonitor.remoteClipboardType), .string], owner: nil)
            assertTrue(ClipboardMonitor.isRemotePasteboard(customPb))
        }

        harness.test("ClipboardPreviewDismissalPolicy respects pin state for preview and popover outside clicks") {
            // Unpinned + preview open + click outside preview -> dismisses both
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: false,
                    isPreviewShown: true,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: false
                ),
                .closePreviewAndPopover
            )
            // Unpinned + preview open + click on underlying popover outside preview -> dismisses both
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: false,
                    isPreviewShown: true,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: true
                ),
                .closePreviewAndPopover
            )
            // Unpinned + preview open + click inside preview -> stays open for interaction
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: false,
                    isPreviewShown: true,
                    isPopoverShown: true,
                    clickedInsidePreview: true,
                    clickedInsidePopover: true
                ),
                .none
            )
            // Pinned + preview open + click outside preview -> neither closes
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: true,
                    isPreviewShown: true,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: false
                ),
                .none
            )
            // Unpinned + preview closed + click outside popover -> dismisses popover
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: false,
                    isPreviewShown: false,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: false
                ),
                .closePreviewAndPopover
            )
            // Unpinned + preview closed + click inside popover -> stays open
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: false,
                    isPreviewShown: false,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: true
                ),
                .none
            )
            // Pinned + preview closed + click outside popover -> stays open
            assertEqual(
                ClipboardPreviewDismissalPolicy.actionForOutsideEvent(
                    isPinned: true,
                    isPreviewShown: false,
                    isPopoverShown: true,
                    clickedInsidePreview: false,
                    clickedInsidePopover: false
                ),
                .none
            )
        }

        harness.test("ClipboardFullImageWindowController computes bounded initial window sizes") {
            let visible = CGRect(x: 0, y: 0, width: 1440, height: 900)

            // Tiny image enforces minimum window dimensions (520 x 400)
            let tiny = ClipboardItem(content: "tiny", type: .image, imageWidth: 120, imageHeight: 80)
            let tinySize = ClipboardFullImageWindowController.initialContentSize(for: tiny, visibleFrame: visible)
            assertEqual(tinySize.width, 520)
            assertEqual(tinySize.height, 400)

            // Medium wide screenshot preserves full width when within 85% of screen
            let medium = ClipboardItem(content: "wide", type: .image, imageWidth: 930, imageHeight: 106)
            let mediumSize = ClipboardFullImageWindowController.initialContentSize(for: medium, visibleFrame: visible)
            assertEqual(mediumSize.width, 930)
            assertEqual(mediumSize.height, 400)

            // Oversized 4K image scales down to at most 85% of visible screen bounds
            let huge = ClipboardItem(content: "huge", type: .image, imageWidth: 3840, imageHeight: 2160)
            let hugeSize = ClipboardFullImageWindowController.initialContentSize(for: huge, visibleFrame: visible)
            assertTrue(hugeSize.width <= floor(visible.width * 0.85))
            assertTrue(hugeSize.height <= floor(visible.height * 0.85))
            assertTrue(hugeSize.width >= 520)
            assertTrue(hugeSize.height >= 400)

            // Missing dimensions fall back cleanly
            let unknown = ClipboardItem(content: "unknown", type: .image)
            let fallbackSize = ClipboardFullImageWindowController.initialContentSize(for: unknown, visibleFrame: visible)
            assertEqual(fallbackSize.width, 760)
            assertEqual(fallbackSize.height, 560)
        }
    }
}
